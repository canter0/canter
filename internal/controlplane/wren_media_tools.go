func wrenMediaTools() []mcpTool {
	str := map[string]string{"type": "string"}
	return []mcpTool{
		{Name: "canter_generate_image", Description: "Generate or edit one actual PNG image only when the human request or saved instruction explicitly requests image creation/editing. Uses the configured managed image provider, consumes the workspace AI allowance, and publishes the actual file here. Existing edits require sourceArtifactId and expectedRevision; conflicts retain the generated bytes privately for explicit recovery. No external publishing. Check the receipt state; running/unknown/failed are not success. Do not retry a request with a fresh key.", InputSchema: map[string]any{"type": "object", "additionalProperties": false, "properties": map[string]any{"mode": map[string]any{"type": "string", "enum": []string{"generate", "edit"}}, "prompt": str, "name": str, "sourceArtifactId": str, "expectedRevision": map[string]string{"type": "integer"}, "shape": map[string]any{"type": "string", "enum": []string{"square", "landscape", "portrait"}}, "transparent": map[string]string{"type": "boolean"}}, "required": []string{"prompt", "name"}}},
		{Name: "canter_image_status", Description: "Read the durable receipt for your image generation operation. Unknown means a provider request may have been accepted and will not be automatically resent.", InputSchema: map[string]any{"type": "object", "additionalProperties": false, "properties": map[string]any{"id": str}, "required": []string{"id"}}},
	}
}
func (o *OperatorRuntime) wrenMediaTool(ctx context.Context, run OperatorRun, c Conversation, name string, raw json.RawMessage) (any, bool, error) {
	if name != "canter_generate_image" && name != "canter_image_status" {
		return nil, false, nil
	}
	s := o.Server.service.Store
	if name == "canter_image_status" {
		var in struct{ ID string }
		if err := json.Unmarshal(raw, &in); err != nil {
			return nil, true, err
		}
		op, err := s.WrenMediaOperation(ctx, c.WorkspaceID, c.AccountID, in.ID)
		if err == nil && op.ConversationID != c.ID {
			return nil, true, ErrForbidden
		}
		return op, true, err
	}
	var in WrenMediaInput
	if err := json.Unmarshal(raw, &in); err != nil {
		return nil, true, err
	}
	// This first image slice deliberately requires a direct accepted human/routine
	// run. Delegated workers can still publish real files from their computer.
	// Keeping the original run is necessary for durable authority and revocation.
	if len(c.ID) >= 9 && c.ID[:9] == "conv_job_" {
		return nil, true, fmt.Errorf("ask the lead Wren to generate the image in the originating chat")
	}
	op, err := o.Server.GenerateWrenMedia(ctx, c, run, in)
	if err == nil && op.ArtifactID != "" {
		err = o.surface(ctx, run, OperatorSurface{Kind: "wren-artifact", ID: op.ArtifactID})
	}
	return op, true, err
}
func (h *HTTPServer) workspaceWrenMedia(w http.ResponseWriter, r *http.Request, p Principal, workspace string, parts []string) {
	if p.Account == nil || p.Installation != nil {
		writeStoreError(w, ErrForbidden)
		return
	}
	account := p.Account.ID
	s := h.service.Store
	if len(parts) == 0 && r.Method == http.MethodGet {
		conversation := r.URL.Query().Get("conversationId")
		ops, err := s.WrenMediaOperations(r.Context(), workspace, account, conversation)
		if err != nil {
			writeStoreError(w, err)
			return
		}
		_, model, configured := h.mediaConfig(r.Context(), workspace, account)
		available := configured == nil && s.RequireWorkspaceWriter(r.Context(), workspace, account) == nil && s.ValidateWrenLifecycleConversation(r.Context(), conversation, "") == nil
		if available {
			available = h.WrenAIRequestAvailable(r.Context(), workspace, WrenAIRequestEstimate{Kind: "media", Model: model}) == nil
		}
		writeJSON(w, 200, map[string]any{"operations": ops, "available": available, "model": model})
		return
	}
	if len(parts) == 0 && r.Method == http.MethodPost {
		var in struct {
			ConversationID string `json:"conversationId"`
			WrenMediaInput
		}
		if !decodeLimit(w, r, &in, 8192) {
			return
		}
		c, err := s.Conversation(r.Context(), workspace, account, in.ConversationID)
		if err != nil {
			writeStoreError(w, err)
			return
		}
		c.AccountID = account
		op, err := h.GenerateWrenMedia(r.Context(), c, OperatorRun{}, in.WrenMediaInput)
		if err != nil {
			writeStoreError(w, err)
			return
		}
		writeJSON(w, 200, op)
		return
	}
	if len(parts) == 1 && r.Method == http.MethodGet {
		op, err := s.WrenMediaOperation(r.Context(), workspace, account, parts[0])
		if err != nil {
			writeStoreError(w, err)
			return
		}
		writeJSON(w, 200, op)
		return
	}
	if len(parts) == 2 && parts[1] == "recover" && r.Method == http.MethodPost {
		op, err := h.publishWrenMedia(r.Context(), workspace, account, parts[0], true)
		if err != nil {
			writeStoreError(w, err)
			return
		}
		writeJSON(w, 200, op)
		return
	}
	http.NotFound(w, r)
}
